// Rule SLOP03: AI Chat Remnants and Conversational Comments
// Detects conversational meta-commentary and agent scratchpad remnants in diffs.

export const id = 'SLOP03_AI_CHAT_REMNANT';
export const name = 'AI Chat Remnant or Conversational Meta-Comment';
export const severity = 'medium';
export const weight = 2.0;

const AI_COMMENT_PATTERNS = [
  // Conversational agent phrasing
  /^\s*(?:\/\/|#|\/\*)\s*(?:Here we\b|In order to avoid\b|Note:\s*This was updated\b|As requested,\s*we\b)/i,
  /^\s*(?:\/\/|#|\/\*)\s*(?:Let's make sure\b|We need to ensure that\b|Now we can safely\b)/i,
  /^\s*(?:\/\/|#|\/\*)\s*(?:This function handles the case where\b|The user asked to\b)/i,

  // Tool / Model attribution left behind
  /^\s*(?:\/\/|#|\/\*)\s*(?:Generated by\s+(?:Claude|Cursor|Copilot|GPT|Aider|Windsurf|v0)\b)/i,
  /^\s*(?:\/\/|#|\/\*)\s*(?:AI-generated\b|LLM fix\b|Agent workaround\b)/i,

  // Test-rigging confessions
  /^\s*(?:\/\/|#|\/\*)\s*(?:Hack to make test pass\b|Workaround for test suite\b|Quick fix to bypass error\b)/i,
  /^\s*(?:\/\/|#|\/\*)\s*(?:Refactored to silence compiler\b|Temporary workaround until real fix\b)/i,

  // Placeholder deferral
  /^\s*(?:\/\/|#|\/\*)\s*(?:TODO:\s*(?:implement actual logic|add real implementation|replace with real data)\b)/i,
  /^\s*(?:\/\/|#|\/\*)\s*(?:FIXME:\s*(?:temporary mock|fake implementation|revisit later)\b)/i
];

export function check({ file, hunk, line, fullContent, isTest }) {
  const text = line.content;
  if (!text || !text.trim()) return null;

  for (const pattern of AI_COMMENT_PATTERNS) {
    if (pattern.test(text)) {
      return {
        ruleId: id,
        ruleName: name,
        severity,
        weight,
        message: 'Diff contains AI conversational phrasing or scratchpad commentary.',
        snippet: text.trim()
      };
    }
  }

  return null;
}
