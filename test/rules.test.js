import test from 'node:test';
import assert from 'node:assert';

import * as assertsRule from '../lib/rules/asserts.js';
import * as errorsRule from '../lib/rules/errors.js';
import * as commentsRule from '../lib/rules/comments.js';
import * as typesRule from '../lib/rules/types.js';
import * as ghostsRule from '../lib/rules/ghosts.js';
import * as mocksRule from '../lib/rules/mocks.js';
import * as leaksRule from '../lib/rules/leaks.js';
import * as noiseRule from '../lib/rules/noise.js';

test('SLOP01_TAUTOLOGICAL_ASSERT detects literal and identity assertions in tests', () => {
  const line1 = { content: 'expect(true).toBe(true);', lineNum: 10 };
  const res1 = assertsRule.check({ line: line1, isTest: true });
  assert.ok(res1, 'Should flag expect(true).toBe(true)');
  assert.strictEqual(res1.ruleId, 'SLOP01_TAUTOLOGICAL_ASSERT');

  const line2 = { content: 'expect(val).toEqual(val);', lineNum: 12 };
  const res2 = assertsRule.check({ line: line2, isTest: true });
  assert.ok(res2, 'Should flag expect(val).toEqual(val)');

  const line3 = { content: 'assert(true);', lineNum: 15 };
  const res3 = assertsRule.check({ line: line3, isTest: true });
  assert.ok(res3, 'Should flag assert(true)');

  const lineClean = { content: 'assert.strictEqual(cart.total, 120);', lineNum: 20 };
  const resClean = assertsRule.check({ line: lineClean, isTest: true });
  assert.strictEqual(resClean, null, 'Clean assertion should not be flagged');
});

test('SLOP02_SWALLOWED_ERROR detects empty catch and swallowed promise rejections', () => {
  const line1 = { content: 'try { doSomething(); } catch (e) {}', lineNum: 5 };
  const res1 = errorsRule.check({ line: line1 });
  assert.ok(res1, 'Should flag empty catch');
  assert.strictEqual(res1.ruleId, 'SLOP02_SWALLOWED_ERROR');

  const line2 = { content: 'fetchData().catch(() => {});', lineNum: 8 };
  const res2 = errorsRule.check({ line: line2 });
  assert.ok(res2, 'Should flag empty promise catch');

  const lineClean = { content: 'catch (err) { throw new AppError(err); }', lineNum: 10 };
  const resClean = errorsRule.check({ line: lineClean });
  assert.strictEqual(resClean, null, 'Catch that rethrows should not be flagged');
});

