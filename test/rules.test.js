test('SLOP05_GHOST_DECLARATION detects unexported and unreferenced declarations', () => {
  const lineGhost = { content: 'const orphanTaxCalc = () => 0.05;', lineNum: 22 };
  const fullContent = 'export function run() { return 1; }\nconst orphanTaxCalc = () => 0.05;\n';
  const res = ghostsRule.check({ line: lineGhost, fullContent });
  assert.ok(res, 'Should flag unreferenced orphan declaration');
  assert.strictEqual(res.ruleId, 'SLOP05_GHOST_DECLARATION');

  const lineUsed = { content: 'const tax = 0.05;', lineNum: 22 };
  const fullContentUsed = 'const tax = 0.05;\nexport function run() { return tax * 10; }\n';
  const resUsed = ghostsRule.check({ line: lineUsed, fullContent: fullContentUsed });
  assert.strictEqual(resUsed, null, 'Used declaration should not be flagged');
});

test('SLOP06_PRODUCTION_MOCK_FALLBACK detects inlined test mocks in production', () => {
  const line1 = { content: "if (process.env.NODE_ENV === 'test') return { ok: true };", lineNum: 5 };
  const res1 = mocksRule.check({ line: line1, isTest: false });
  assert.ok(res1, 'Should flag NODE_ENV === test in production');
  assert.strictEqual(res1.ruleId, 'SLOP06_PRODUCTION_MOCK_FALLBACK');

  // Should ignore in test files
  const resTest = mocksRule.check({ line: line1, isTest: true });
  assert.strictEqual(resTest, null, 'Should not flag in test file');
});

test('SLOP07_LOCAL_PATH_LEAK detects machine paths and leaked tokens', () => {
  const line1 = { content: "const logFile = '/Users/developer/app.log';", lineNum: 8 };
  const res1 = leaksRule.check({ line: line1 });
  assert.ok(res1, 'Should flag /Users/ path');
  assert.strictEqual(res1.ruleId, 'SLOP07_LOCAL_PATH_LEAK');

  const line2 = { content: "const apiKey = 'sk-1234567890abcdef1234567890';", lineNum: 9 };
  const res2 = leaksRule.check({ line: line2 });
  assert.ok(res2, 'Should flag OpenAI secret token');

  const lineClean = { content: "const apiKey = process.env.API_KEY;", lineNum: 10 };
  const resClean = leaksRule.check({ line: lineClean });
  assert.strictEqual(resClean, null, 'Clean env reference should not be flagged');
});

test('SLOP08_COLLATERAL_DIFF_NOISE detects trailing whitespace', () => {
  const line1 = { content: 'const x = 10;   ', lineNum: 3 };
  const res1 = noiseRule.check({ line: line1, hunk: { lines: [line1] } });
  assert.ok(res1, 'Should flag trailing spaces');
  assert.strictEqual(res1.ruleId, 'SLOP08_COLLATERAL_DIFF_NOISE');
});
